import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const engine = fs.readFileSync('web/catalog-experience-engine.js', 'utf8');
const digitalHtml = fs.readFileSync('web/digital-page-self-service.html', 'utf8');
const digitalJs = fs.readFileSync('web/digital-page-self-service.js', 'utf8');
const publicPageHtml = fs.readFileSync('web/digital-page.html', 'utf8');
const publicPageJs = fs.readFileSync('web/digital-page.js', 'utf8');
const marketingHtml = fs.readFileSync('web/marketing-services.html', 'utf8');
const marketingJs = fs.readFileSync('web/marketing-services.js', 'utf8');
const smmHtml = fs.readFileSync('web/smm.html', 'utf8');
const app = fs.readFileSync('web/app.js', 'utf8');
const index = fs.readFileSync('web/index.html', 'utf8');
const sw = fs.readFileSync('web/sw.js', 'utf8');
const sectors = fs.readFileSync('web/sector-registry.js', 'utf8');
const sectorModules = fs.readFileSync('web/sector-modules.js', 'utf8');
const operationsModules = fs.readFileSync('web/operations-modules.js', 'utf8');

for (const code of ['FOOD','PHARMACY','HEALTH','DENTAL','MEDICAL','HOSPITAL','LABS','RADIOLOGY','COMPANIES','FREELANCER','MAINTENANCE','GROCERY','FASHION','MARKETING','REAL_ESTATE','AUTO','VETERINARY','EDUCATION','ERP','ACCOUNTING','LEGAL','SPORTS','TRIPS','MANTIGO','FACTORIES','JOBS','MATRIMONY','USED_ITEMS']) {
  assert.ok(engine.includes(code + ': Object.freeze') || engine.includes("'" + code + "': Object.freeze"), 'missing sector adapter profile ' + code);
}
assert.match(engine, /function profileFor/);
assert.match(engine, /PROFILE_ALIASES/);
assert.match(engine, /PUBLIC_TO_BACKEND_SECTOR/);
assert.match(engine, /requestMode: 'EXISTING_RIDE_FLOW'/);
assert.match(engine, /requestMode: 'EXISTING_LISTING_FLOW'/);
assert.match(engine, /function escapeHtml/);
assert.match(engine, /!\['WHATSAPP', 'WHATSAPP_INFORMATION_ONLY'\]\.includes\(p\.requestMode\)/, 'generic WhatsApp inquiry must not bypass existing booking, ride, job, or matching flows');
assert.match(engine, /encodeURIComponent/);
assert.match(engine, /UNDER_CONSTRUCTION: \{ label: 'تحت الإنشاء'/);
assert.match(engine, /requestMode: 'INFORMATION_ONLY'/, 'high-risk sector may use information-only rather than generic order');
assert.match(engine, /preserve: \['pharmacist-review', 'prescription-controls', 'regulated-products'\]/);
assert.match(engine, /preserve: \['departments', 'emergency-routing', 'patient-privacy', 'institutional-workflow'\]/);
assert.match(engine, /function subscriptionDisplay/);
assert.match(engine, /function renderCatalogItem/);
assert.match(engine, /function renderCatalog\(/);
assert.match(engine, /rows\.slice\(0, 200\)/, 'shared renderer must bound item count');
assert.match(engine, /Never use this function to grant access or publish a page/);
assert.match(digitalHtml, /catalog-experience-engine\.js/);
assert.match(digitalJs, /loadSubscriptionReminders/);
assert.match(digitalJs, /digital_page_subscription_active/);
assert.match(digitalJs, /تعذر التحقق من مواعيد الاشتراك/);
assert.match(marketingHtml, /catalog-experience-engine\.js/);
assert.match(marketingJs, /MNTYCatalogExperience\?\.whatsappUrl/);
assert.match(index, /load\('catalog-experience-engine\.js\?v=launch-catalog-engine-3'\);\s*await load\('app\.js\?v=launch-catalog-engine-3'\);/, 'load shared engine before dashboard/module runtime');
assert.match(sw, /catalog-experience-engine\.js\?v=launch-catalog-engine-3/);
assert.match(sw, /app\.js\?v=launch-catalog-engine-3/);
assert.match(sectors, /CANONICAL_SECTORS/);
assert.match(sectorModules, /function shell\(d,body\)/);
assert.match(operationsModules, /const defs=/);
assert.match(app, /function subscriptionReminderPanel\(\)/);
assert.match(app, /daysLeft<=3\?'urgent'/, '3-day expiry milestone must be highlighted');
assert.match(app, /daysLeft<=1\?'critical'/, '1-day expiry milestone must be highlighted');
assert.match(app, /متاحة — طلب الخدمة عبر واتساب/, 'implemented marketing service page must not be mislabeled under construction');
assert.match(app, /case'الإشعارات':return subscriptionReminderPanel\(\)/);
assert.match(smmHtml, /smm\.js/);
assert.doesNotMatch(engine, /smm-gateway|payment-intent|paymob/i, 'shared public catalog engine must not execute SMM or payment operations');

const runtime = { console, Date, URL, encodeURIComponent };
runtime.window = runtime;
runtime.globalThis = runtime;
vm.createContext(runtime);
vm.runInContext(sectors, runtime, { filename: 'web/sector-registry.js' });
vm.runInContext(engine, runtime, { filename: 'web/catalog-experience-engine.js' });
const shared = runtime.MNTYCatalogExperience;
for (const sector of runtime.MX_SECTOR_REGISTRY.CANONICAL_SECTORS) {
  assert.ok(shared.profileFor(sector.code), 'canonical sector missing shared adapter: ' + sector.code);
}
assert.equal(shared.profileFor('FOOD').code, 'FOOD');
assert.equal(shared.profileFor('DIGITAL').code, 'MARKETING');
assert.equal(shared.profileFor('EDU').code, 'EDUCATION');
assert.equal(shared.profileFor('TECH').code, 'ERP');
assert.equal(shared.profileFor('PHARMACY').requestMode, 'WHATSAPP');
assert.equal(shared.buildInquiry('FOOD', '201010171770', { name: 'قهوة', price: '50' }, 'https://example.invalid/menu').startsWith('https://wa.me/201010171770?text='), true);
assert.equal(shared.buildInquiry('HEALTH', '201010171770', { name: 'كشف' }, 'https://example.invalid/clinic'), null, 'medical inquiries must use the existing booking workflow');
assert.equal(shared.buildInquiry('MANTIGO', '201010171770', { name: 'رحلة' }, 'https://example.invalid/ride'), null, 'rides must use the existing ride workflow');
assert.equal(shared.buildInquiry('JOBS', '201010171770', { name: 'وظيفة' }, 'https://example.invalid/jobs'), null, 'job applications must use the existing application workflow');
assert.equal(shared.profileFor('HOSPITAL').requestMode, 'INFORMATION_ONLY');
assert.equal(shared.profileFor('MANTIGO').requestMode, 'EXISTING_RIDE_FLOW');
assert.equal(shared.profileFor('UNKNOWN'), null);
assert.equal(shared.statuses.UNDER_CONSTRUCTION.enabled, false);
assert.equal(shared.statuses.NOT_VERIFIED.enabled, false);
const safeCard = shared.renderCatalogItem('FOOD', {name:'<script>alert(1)</script>',description:'Tea',price:25}, {phone:'201010171770',pageUrl:'https://example.invalid/menu'});
assert.ok(safeCard.includes('&lt;script&gt;alert(1)&lt;/script&gt;'), 'shared catalog renderer must escape item names');
assert.ok(!safeCard.includes('<script>alert(1)</script>'), 'shared catalog renderer must not render executable markup');
assert.ok(safeCard.includes('https://wa.me/201010171770?text='), 'WhatsApp-enabled sectors must receive the shared CTA');
assert.ok(shared.renderCatalogItem('HEALTH', {name:'كشف'}, {phone:'201010171770'}).includes('المسار المعتمد'), 'medical listings must not bypass the existing booking flow');
assert.ok(shared.renderCatalogItem('FOOD', {name:'غير جاهز'}, {status:'UNDER_CONSTRUCTION',phone:'201010171770'}).includes('تحت الإنشاء'), 'under-construction items must not expose ready actions');
assert.ok(shared.renderCatalog('FOOD', []).includes('لا توجد عناصر منشورة'), 'empty catalogs must have a clear empty state');
assert.equal(shared.whatsappUrl('123', 'test'), null);
const wa = shared.whatsappUrl('+20 100 000 0000', 'طلب صنف & تفاصيل');
assert.ok(wa.startsWith('https://wa.me/201000000000?text='));
assert.ok(wa.includes(encodeURIComponent('طلب صنف & تفاصيل')));
const expiry = shared.subscriptionDisplay({ paymentStatus: 'PAID', paidAt: '2026-01-01T00:00:00.000Z', durationDays: 30 }, Date.parse('2026-01-25T00:00:00.000Z'));
assert.equal(expiry.state, 'EXPIRING');
assert.equal(expiry.daysRemaining, 6);
assert.equal(shared.subscriptionDisplay({ paymentStatus: 'PENDING', paidAt: null, durationDays: 30 }).state, 'PENDING_REVIEW');
assert.equal(shared.subscriptionDisplay({ paymentStatus: 'PAID', paidAt: null, durationDays: 30 }).state, 'NOT_VERIFIED');

console.log('Shared catalog engine profile runtime + WhatsApp helper + subscription reminder source contracts: PASS');
