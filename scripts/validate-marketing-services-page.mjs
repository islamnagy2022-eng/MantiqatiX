import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('web/marketing-services.html','utf8');
const home=fs.readFileSync('web/home.js','utf8');
const app=fs.readFileSync('web/app.js','utf8');
const sw=fs.readFileSync('web/sw.js','utf8');
assert.match(html,/<html lang="ar" dir="rtl">/);
assert.match(html,/الخدمات التسويقية تحت الإنشاء/);
assert.match(html,/noindex,nofollow/);
assert.match(html,/صفحات الكتالوج/);
assert.doesNotMatch(html,/id="request-form"|data-wa-general|marketing-services\.js/);
assert.doesNotMatch(home,/href="marketing-services\.html"/,'homepage must not advertise the deferred marketing services page');
assert.doesNotMatch(app,/href="marketing-services\.html"/,'authenticated dashboard must not advertise the deferred marketing services page');
assert.match(app,/صفحة الخدمات التسويقية مؤجلة/,'dashboard must label the marketing page as deferred');
assert.match(home,/صفحة الخدمات التسويقية مؤجلة/);
assert.match(home,/خدمات التسويق — تحت الإنشاء/);
assert.match(home,/الإعلانات الممولة مؤجلة لما بعد الإطلاق الأول/);
assert.match(home,/querySelectorAll\('#mx-growth-ads,#mx-ad-book,#mx-ad-cta,#mx-ad-plans,\[data-ad-plan\]'\)/,'all public sponsored-ad purchase controls must be disabled');
assert.match(sw,/const CACHE='mnty-web-v[0-9]+[^']*';/,'PWA cache must use an explicit versioned cache key');
assert.doesNotMatch(sw,/const CACHE='mnty-web-v140-catalog-first';/,'PWA cache must not regress to the obsolete catalog-first cache version');
assert.doesNotMatch(sw,/\.\/marketing-services\.html|\.\/marketing-services\.css|\.\/marketing-services\.js/,'deferred marketing page assets must not be precached');
console.log('Deferred marketing services contract: PASS');
console.log('Public homepage contains no active link to the deferred marketing services page.');
