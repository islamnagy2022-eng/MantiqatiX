import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";

const migrations = readdirSync(new URL("../supabase/migrations/", import.meta.url));
const migrationName = migrations.find((name) =>
  /^\d{14}_rc932_mantigo_open_ride_explicit_confirmed_auth\.sql$/.test(name)
);
assert.ok(migrationName, "RC932 migration must be generated by the pinned Supabase CLI");
const migration = readFileSync(new URL("../supabase/migrations/" + migrationName, import.meta.url), "utf8");
const integration = readFileSync(new URL("../supabase/tests/rc932_mantigo_open_ride_explicit_confirmed_auth_integration.sql", import.meta.url), "utf8");

for (const marker of [
  "CREATE OR REPLACE FUNCTION public.list_open_mantigo_rides_backend",
  "(auth.jwt()->>'is_anonymous') IS DISTINCT FROM 'false'",
  "MANTIGO_AUTH_REQUIRED",
  "MANTIGO_CAPTAIN_PROFILE_REQUIRED",
  "cp.status='ACTIVE'",
  "cp.verification_status='VERIFIED'",
  "cp.availability_status='AVAILABLE'",
  "r.vehicle_category=v_vehicle_category",
  "SET search_path = pg_catalog",
  "REVOKE ALL ON FUNCTION public.list_open_mantigo_rides_backend(uuid) FROM PUBLIC,anon",
  "GRANT EXECUTE ON FUNCTION public.list_open_mantigo_rides_backend(uuid) TO authenticated"
]) {
  assert.ok(migration.includes(marker), "RC932 migration missing strict boundary: " + marker);
}
assert.doesNotMatch(
  migration,
  /coalesce\s*\(\s*\(\s*auth\.jwt\(\)\s*->>\s*'is_anonymous'/i,
  "RC932 must not coalesce a missing/null identity claim to confirmed"
);
for (const marker of [
  "RC932 anon EXECUTE must remain denied",
  "RC932 authenticated EXECUTE must remain enabled",
  "request.jwt.claims','{}'",
  "request.jwt.claims','{\"is_anonymous\":null}'",
  "request.jwt.claims','{\"is_anonymous\":true}'",
  "request.jwt.claims','{\"is_anonymous\":false}'",
  "RC932 missing is_anonymous claim was allowed",
  "RC932 null is_anonymous claim was allowed",
  "RC932 anonymous Auth identity was allowed",
  "RC932 confirmed captain compatibility failed"
]) {
  assert.ok(integration.includes(marker), "RC932 integration missing: " + marker);
}
console.log("RC932 explicit confirmed identity source contract: PASS");

